// ── Safe render helpers — prevents function() appearing in UI ────────────
window.safeText = function(value, fallback) {
  fallback = fallback || '';
  if (value === null || value === undefined) return fallback;
  if (typeof value === 'string') return value;
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return String(value);
  return fallback;
};

window.getSafeIcon = function(input) {
  try {
    if (!input) return '✨';
    if (typeof input === 'string') return input;
    var opts = input || {};
    if (opts.icon && window.AF_ICONS && window.AF_ICONS[opts.icon]) {
      var found = window.AF_ICONS[opts.icon];
      if (typeof found === 'function') {
        var result = found(opts);
        return typeof result === 'string' ? result : '✨';
      }
      if (typeof found === 'string') return found;
    }
    if (opts.emoji) return String(opts.emoji);
    return '✨';
  } catch (err) {
    console.warn('[Icons] getSafeIcon failed', err.message);
    return '✨';
  }
};

window.normalizeUiValue = function(value, fallback) {
  fallback = fallback || '';
  if (value === null || value === undefined) return fallback;
  if (typeof value === 'function') {
    try { var r = value(); return typeof r === 'string' ? r : fallback; }
    catch(e) { return fallback; }
  }
  if (typeof value === 'object') return fallback;
  return String(value);
};

